/* Sunken Crypt: the co-op dungeon (sim/dungeon/, docs/dungeon-plan.md).
   Seven rooms in a line joined by short corridors: the top row runs east
   from the Antechamber (where the party spawns) through the Bone Halls
   and the Ossuary to the Webbed Galleries; a passage drops south to the
   Brood Nest, and the bottom row runs back west over the lava of the
   Ashen Causeway to the Throne of Dust.

   CryptRooms is the same size as the layout and is read only by the
   dungeon: a digit is the room a tile belongs to (1 to 7), a letter the
   gate between two rooms (A between 1 and 2, B between 2 and 3, and so
   on), '.' neither. Gates are open floor here; the dungeon closes them
   with walls while a room's monsters live. No monsters roam: the
   dungeon places every one. Drawn by a script, like the other
   hand-made maps. */
