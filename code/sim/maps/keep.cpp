DefineMap_Keep(map_def *Map)
{
    Map->Name = "Frostbite Keep";
    Map->Kind = MapKind_Bounded;
    Map->Seed = 4121;
    Map->Layout = KeepLayout;
    Map->Width = 64;
    Map->Height = ArrayCount(KeepLayout);
    Map->Outside = TerrainKind_StoneWall;
    Map->MonsterWeight[MonsterKind_Shade] = 3.f;
    Map->MonsterWeight[MonsterKind_Shaman] = 3.f;
    Map->MonsterWeight[MonsterKind_Warden] = 2.5f;
    Map->MonsterWeight[MonsterKind_Imp] = 0.f;
    Map->MonsterWeight[MonsterKind_Toad] = 0.f;
    Map->MonsterWeight[MonsterKind_Lurker] = 0.f;
    Map->MonsterWeight[MonsterKind_Warlord] = 0.f;
}

