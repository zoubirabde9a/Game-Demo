/* Rimeheart Vault: the third level of the co-op dungeon (sim/dungeon/,
   docs/dungeon-vault.md), reached by clearing the Ember Depths. A vault
   of black ice under the forge, where the cold that put the fires out
   still sleeps. Seven rooms: the party arrives in Frostgate Landing on
   the west, crosses the snow of the Shiver Hall, climbs north to the
   Calving Hall, goes east through the flooded Drowned Cloister, drops
   south into the round Mirror Mere, then south again onto the Shattered
   Span, a causeway over a frozen lake cracked open to black water, which
   runs west to the Rimeheart Throne.

   Ice is slow to start on and slow to stop on, so a shove carries a long
   way; the cracks are deep water, slow to wade out of. They were pits
   first, and bots sliding on the ice fell in every few seconds. Runes in
   the boss rooms lift the slows the bosses put on.

   VaultRooms works like CryptRooms (sim/maps/crypt.cpp): a digit is the
   room a tile belongs to, a letter the gate between two rooms, '.'
   neither. Drawn by a script, like the other hand-made maps. */
