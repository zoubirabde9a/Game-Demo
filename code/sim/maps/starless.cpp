/* The Starless Deep: the fifth level of the co-op dungeon (sim/dungeon/,
   docs/dungeon-starless.md), reached by clearing the Aurora Rift. Under
   the glacier lies what the aurora was the light of: a star that fell and
   burned out, still pulling at everything round it. Black basalt and old
   stone, crags of broken rock, runes still lit. Seven rooms: the party
   arrives at the Fallen Gate on the west, crosses the Hall of Whispers,
   goes east into the Maw, south into the Shattered Orrery, west into the
   Obsidian Court, south onto the Brink, and east to the Throne of the
   Black Sun.

   The deep is drawn for what its monsters do. Gravity wells drag players
   about, so the boss rooms of the well-casters are open floor with
   nothing to snag on; the Brink is a causeway through crag (slow
   ground), so a well that drags someone off it costs them seconds to
   walk back. The Hall of Whispers and the Throne are long halls with
   room to spread out from a void brand, and pillars in the Throne to
   hide from beams. Runes in every boss room lift slows.

   StarlessRooms works like CryptRooms (sim/maps/crypt.cpp): a digit is
   the room a tile belongs to, a letter the gate between two rooms, '.'
   neither. Drawn by a script, like the other hand-made maps. */
