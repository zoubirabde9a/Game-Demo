/* Aurora Rift: the fourth level of the co-op dungeon (sim/dungeon/,
   docs/dungeon-rift.md), reached by clearing the Rimeheart Vault. A
   crevasse in a glacier open to the polar sky, where the aurora fell and
   froze into crystal. Seven rooms: the party arrives in the Rift Mouth on
   the west, crosses the Hoarfrost Gallery, goes east into the Avalanche
   Den, drops south into the long Lightfall Crevasse, west into the Prism
   Sanctum, south onto the Starfrost Bridge over black water, and east to
   the Everwinter Throne.

   The rift is drawn for what its monsters do. Waves of frost roll
   through walls, so the rooms where they come have open floor to land
   jumps on; beams of light stop at walls, so the halls of the beam
   casters are full of pillars to hide behind. Snow slows, ice carries a
   shove, deep water is slow to wade out of; runes in the Sanctum and the
   Throne lift slows.

   RiftRooms works like CryptRooms (sim/maps/crypt.cpp): a digit is the
   room a tile belongs to, a letter the gate between two rooms, '.'
   neither. Drawn by a script, like the other hand-made maps. */
